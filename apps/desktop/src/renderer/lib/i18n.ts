const DICTS: Record<Locale, Dict | null> = { 'en-US': en, 'de-DE': de, pseudo: null };

let currentLocale: Locale = 'en-US';

export function setLocale(l: Locale): void {
  currentLocale = l;
}

export function locale(): Locale {
  return currentLocale;
}

/** Translate `id` with `{placeholder}` interpolation. Missing ids fall back
 * to en, then to the id itself (visible, never a crash). */
export function t(id: string, vars?: Record<string, string | number>): string {
  let s = DICTS[currentLocale]?.[id] ?? en[id] ?? id;
  if (currentLocale === 'pseudo') {
    s = `[!! ${s} !!]`;
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
